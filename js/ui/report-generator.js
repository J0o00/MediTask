// PDF progress report for the physiotherapist (jsPDF, loaded globally).
import { METRIC_LABEL, fmtDate, fmtDateTime } from './dom.js';

export function exportPatientReport(patient, twin, sessions, alerts = []) {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();
    let y = 20;
    const line = (txt, size = 10, color = [50, 50, 50], indent = 20) => {
        if (y > 278) { doc.addPage(); y = 20; }
        doc.setFontSize(size); doc.setTextColor(...color);
        const parts = doc.splitTextToSize(String(txt), 190 - indent);
        doc.text(parts, indent, y);
        y += parts.length * (size * 0.45 + 1.6);
    };
    const gap = (h = 4) => { y += h; };

    line('MediTask - Rehabilitation Progress Report', 18, [20, 150, 140]);
    line(`Patient: ${patient.displayName || ''} <${patient.email}>`, 11);
    line(`Generated: ${new Date().toLocaleString()}   ·   Sessions on record: ${twin.totalSessions}   ·   Active days (last 14): ${twin.activeDaysLast14}`, 9, [110, 110, 110]);
    doc.setDrawColor(20, 184, 166); doc.line(20, y, 190, y); gap(6);

    if (twin.flags.length || alerts.length) {
        line('Items for review', 13, [180, 60, 40]);
        for (const f of twin.flags) line(`• ${f.message}`, 10, [150, 50, 40], 24);
        for (const a of alerts) line(`• [${a.type}] ${a.message} (${fmtDateTime(a.createdAt)})`, 10, [150, 50, 40], 24);
        gap();
    }

    for (const ex of Object.values(twin.exercises)) {
        line(`${ex.name}  -  ${ex.sessions} session(s)`, 13, [30, 30, 30]);
        const b = ex.baseline, c = ex.current, ch = ex.change;
        const fmt = (v, u = '') => (v === null || v === undefined ? 'n/a' : `${v}${u}`);
        line(`Primary joint: ${METRIC_LABEL[ex.primaryJoint] || ex.primaryJoint || '-'}`, 10, [90, 90, 90], 24);
        line(`ROM      baseline ${fmt(b.rom, '°')} -> recent ${fmt(c.rom, '°')}   (change ${fmt(ch.rom, '°')})`, 10, [50, 50, 50], 24);
        line(`Quality  baseline ${fmt(b.quality)} -> recent ${fmt(c.quality)}   (change ${fmt(ch.quality)})`, 10, [50, 50, 50], 24);
        line(`Pain     baseline ${fmt(b.pain)} -> recent ${fmt(c.pain)}   (change ${fmt(ch.pain)})`, 10, [50, 50, 50], 24);
        if (c.symmetry !== null) line(`L-R asymmetry  baseline ${fmt(b.symmetry, '°')} -> recent ${fmt(c.symmetry, '°')}`, 10, [50, 50, 50], 24);
        gap(2);
    }

    gap(2);
    line('Recent sessions', 13, [30, 30, 30]);
    for (const s of sessions.slice(0, 20)) {
        const sm = s.summary || {};
        const pain = s.feedback ? `pain ${s.feedback.pain}/10, ${s.feedback.difficulty}` : 'no feedback';
        line(`${fmtDate(s.startedAt)}  ${s.exercise}  [${s.status}]  reps ${s.validReps}/${(s.targetSets || 0) * (s.targetReps || 0)}  quality ${sm.avgQuality ?? '-'}  consistency ${sm.consistency ?? '-'}%  ${pain}${s.emergencyStop ? '  [STOP pressed]' : ''}`, 9, [60, 60, 60], 24);
        if (s.feedback?.notes) line(`Patient note: ${s.feedback.notes}`, 8, [110, 110, 110], 30);
    }

    y = Math.max(y, 270); if (y > 285) { doc.addPage(); y = 270; }
    line('Generated by MediTask. Webcam-based measurements are not clinically validated and must be interpreted by a qualified physiotherapist.', 7, [150, 150, 150]);
    doc.save(`MediTask_Report_${(patient.email || 'patient').split('@')[0]}_${new Date().toISOString().slice(0, 10)}.pdf`);
}
