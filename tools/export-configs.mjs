// Export the JS exercise configuration to JSON for the Python ML pipeline,
// so the rule-based baseline in Python uses exactly the same thresholds.
//   node tools/export-configs.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXERCISES, REP_THRESHOLDS } from '../js/rehabilitation/exercise-configs.js';
import { FEATURE_ANGLES } from '../js/rehabilitation/angle-calculator.js';
import { JOINTS, MEDIAPIPE_INDEX } from '../js/rehabilitation/skeleton.js';
import { SEQ_LEN, NUM_FEATURES, PHASE_LABELS, featureNames } from '../js/intelligence/feature-extractor.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../ml/config/exercises.json');
mkdirSync(dirname(out), { recursive: true });
const strip = ({ steps, cues, emoji, ...rest }) => rest;
const data = {
    _comment: 'GENERATED by tools/export-configs.mjs from js/rehabilitation/exercise-configs.js - do not edit by hand.',
    rep_thresholds: REP_THRESHOLDS,
    exercises: Object.fromEntries(Object.entries(EXERCISES).map(([k, v]) => [k, strip(v)])),
    feature_spec: { joints: JOINTS, mediapipe_index: MEDIAPIPE_INDEX, feature_angles: FEATURE_ANGLES, seq_len: SEQ_LEN, num_features: NUM_FEATURES, phase_labels: PHASE_LABELS, feature_names: featureNames() },
};
writeFileSync(out, JSON.stringify(data, null, 2) + '\n');
console.log(`wrote ${out}`);
